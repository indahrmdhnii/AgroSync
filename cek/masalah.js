const { chromium } = require('playwright');
const L = require('path').resolve(__dirname, '..');
const [,, W = 1280, H = 900, n = 'MD', kar = 'tata', tema = 'light'] = process.argv;
(async () => {
  const b = await chromium.launch();
  const hp = +W < 900;
  const p = await (await b.newContext({ viewport: { width: +W, height: +H }, hasTouch: hp, isMobile: hp })).newPage();
  await p.addInitScript(([k, t]) => { try { localStorage.setItem('agrosync-karakter', k); localStorage.setItem('agrosync-tema', t); } catch (e) {} }, [kar, tema]);
  const galat = []; p.on('pageerror', (e) => galat.push(e.message));
  await p.route('https://**/*', (r) => r.abort());
  await p.goto('file://' + L + '/dist/index.html'); await p.waitForTimeout(1500);
  await p.evaluate(() => scrollTo(0, document.getElementById('masalah').offsetTop - 70)); await p.waitForTimeout(1500);
  await p.screenshot({ path: `${L}/cek/${n}-0.png` });
  const kartu = p.locator('.kartu-bos');
  await kartu.nth(0).click(); await p.waitForTimeout(300);
  await p.screenshot({ path: `${L}/cek/${n}-1kena.png` });
  await p.waitForTimeout(900);
  await kartu.nth(1).click(); await p.waitForTimeout(1200);
  await kartu.nth(2).click(); await p.waitForTimeout(1600);
  await p.screenshot({ path: `${L}/cek/${n}-3beres.png`, fullPage: false });
  console.log(n, JSON.stringify(await p.evaluate(() => ({ tahap: tahapMasalah, gel: document.getElementById('gelembung-masalah').textContent, strip: !document.getElementById('strip-beres').hidden, misi: HADIAH.misi, lebar: document.documentElement.scrollWidth }))));
  await p.click('#strip-beres'); await p.waitForTimeout(1200);
  console.log(n, 'setelah strip, demo di atas layar:', await p.evaluate(() => Math.round(document.getElementById('demo').getBoundingClientRect().top)));
  console.log(galat.join('\n') || 'tanpa galat');
  await b.close();
})();
