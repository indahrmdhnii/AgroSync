const { chromium } = require('playwright');
const L = require('path').resolve(__dirname, '..');
const [,, W = 1280, H = 900, n = 'LD'] = process.argv;
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
  const hp = +W < 900;
  const p = await (await b.newContext({ viewport: { width: +W, height: +H }, hasTouch: hp, isMobile: hp })).newPage();
  await p.addInitScript(() => { try { localStorage.setItem('agrosync-karakter', 'tata'); } catch (e) {} });
  const galat = []; p.on('pageerror', (e) => galat.push(e.message));
  await p.route('https://cdnjs.cloudflare.com/**/three.min.js', (r) => r.fulfill({ path: L + '/vendor/three-r128.min.js', contentType: 'text/javascript' }));
  await p.route('https://fonts.**/**', (r) => r.abort());
  await p.goto('file://' + L + '/dist/index.html'); await p.waitForTimeout(2500);
  await p.evaluate(() => document.getElementById('penjelasan').scrollIntoView({ block: 'center' })); await p.waitForTimeout(800);
  const info = () => p.evaluate(() => ({ penunjuk: !document.getElementById('penunjuk').hidden, cincin: document.querySelectorAll('#hp-layar .ketuk-sini').length, tombol: document.getElementById('pj-panduan').textContent, panduan: S.panduan }));
  console.log(n, 'awal', JSON.stringify(await info()));
  await p.click('#pj-panduan'); await p.waitForTimeout(500);
  await p.evaluate(() => document.getElementById('panggung').scrollIntoView({ block: 'start' })); await p.waitForTimeout(800);
  console.log(n, 'dilewati', JSON.stringify(await info()));
  await p.screenshot({ path: `${L}/cek/${n}-bebas.png` });
  await p.click('#hp-tg-pompa'); await p.waitForTimeout(800); console.log(n, 'simpan sebelum muat ulang:', await p.evaluate(() => localStorage.getItem('agrosync-panduan')));
  console.log(n, 'bebas pencet pompa ->', await p.evaluate(() => S.layar));
  await p.reload(); await p.waitForTimeout(2500);
  console.log(n, 'muat ulang', JSON.stringify(await info()), await p.evaluate(() => localStorage.getItem('agrosync-panduan')));
  await p.evaluate(() => document.getElementById('penjelasan').scrollIntoView({ block: 'center' })); await p.waitForTimeout(500);
  await p.click('#pj-panduan'); await p.waitForTimeout(500);
  await p.evaluate(() => document.getElementById('panggung').scrollIntoView({ block: 'start' })); await p.waitForTimeout(800);
  console.log(n, 'panduan lagi', JSON.stringify(await info()));
  console.log(galat.join('\n') || 'tanpa galat');
  await b.close();
})();
